"""Builds CHANGELOG.md from site/releases.json.

usage: python3 scripts/gen_changelog.py [--check]

site/releases.json is the single source of release notes. scripts/gen_site_changelog.py
turns it into site/changelog.html and site/ko/changelog.html; this script turns the same
data into the repository CHANGELOG.md. `--check` exits non-zero when the file on disk
differs from the data, so a release that forgot to regenerate fails site_gate.sh instead
of drifting.

Both generators share one validator: importing load() from gen_site_changelog keeps the
version/date/ko+en rules in one place.
"""
import re
import sys

from gen_site_changelog import load

DATA = 'site/releases.json'
OUT = 'CHANGELOG.md'
REPO = 'https://github.com/zzcx88/neo3ds'

HEADER = """# Changelog

<!-- Generated by scripts/gen_changelog.py from site/releases.json. Do not edit by hand. -->

All notable changes to neo3ds, newest first. Version sections and dates follow
[Keep a Changelog](https://keepachangelog.com/en/1.1.0/); entries are not split into
Added/Changed/Fixed because `%(data)s` does not classify them. Downloads and release
assets: [GitHub releases](%(releases)s).

Korean text for every release: [site/ko/changelog.html](site/ko/changelog.html).
"""


def link_issues(s):
    """`#177` in a note becomes a link to the issue; everything else stays as written."""
    return re.sub(r'(?<![\w/.-])#(\d+)', lambda m: '[#%s](%s/issues/%s)' % (m.group(1), REPO, m.group(1)), s)


def render(releases):
    out = [HEADER % {'data': DATA, 'releases': REPO + '/releases'}]
    for r in releases:
        out.append('## [%s](%s/releases/tag/v%s) - %s\n' % (r['version'], REPO, r['version'], r['date']))
        for it in r['items']:
            out.append('- **%s** — %s' % (link_issues(it['t']['en']), link_issues(it['d']['en'])))
        out.append('')
    return '\n'.join(out)


def main(argv):
    releases = load()
    text = render(releases)
    if '--check' in argv[1:]:
        try:
            current = open(OUT, encoding='utf-8').read()
        except FileNotFoundError:
            sys.exit('%s: missing, run python3 scripts/gen_changelog.py' % OUT)
        if current != text:
            sys.exit('%s: stale, run python3 scripts/gen_changelog.py' % OUT)
        print('%s is current' % OUT)
        return
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(text)
    print('%s: %d releases, %d bytes' % (OUT, len(releases), len(text)))


if __name__ == '__main__':
    main(sys.argv)
